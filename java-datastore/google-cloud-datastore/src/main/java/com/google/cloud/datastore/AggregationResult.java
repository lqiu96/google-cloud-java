package com.google.cloud.datastore;

import com.google.common.base.MoreObjects;
import com.google.common.base.MoreObjects.ToStringHelper;
import java.util.Map;
import java.util.Map.Entry;
import java.util.Objects;

/**
 * Represents a result of an {@link AggregationQuery} submission, keyed by the alias provided via
 * {@code .as(alias)} (or autogenerated {@code property_<n>} aliases when omitted).
 *
 * <p>When an {@code avg} aggregation matches zero entities (or no matching entities contain a
 * numeric value for the target property), Datastore returns a null value ({@link ValueType#NULL}),
 * whereas {@code count} and {@code sum} return {@code 0}. Because {@link #getLong(String)}, {@link
 * #getDouble(String)}, and {@link #getNumber(String)} only accept numeric ({@link ValueType#LONG}
 * and {@link ValueType#DOUBLE}) values, reading a null {@code avg} result throws a {@link
 * RuntimeException} and reading an absent alias throws {@link NullPointerException}. Pair {@code
 * avg} with a {@code count} aggregation or guard against zero matches when results may be empty.
 *
 * @see <a href="https://docs.cloud.google.com/datastore/docs/aggregation-queries">Datastore
 *     aggregation queries</a>
 */
public class AggregationResult {

  private final Map<String, ? extends Value<?>> properties;

  public AggregationResult(Map<String, ? extends Value<?>> properties) {
    this.properties = properties;
  }

  /**
   * Returns a result value for the given alias. {@link #getLong(String)} is preferred over this
   * method.
   *
   * <p>Use {@link #getLong(String)} wherever possible. See this <a
   * href="https://github.com/googleapis/java-datastore/issues/1175">issue</a> for more details.
   *
   * @param alias A custom alias provided in the query or an autogenerated alias in the form of
   *     'property_\d'
   * @return An aggregation result value for the given alias.
   * @deprecated Use {@link #getLong(String)} instead.
   */
  @Deprecated
  public Long get(String alias) {
    return getLong(alias);
  }

  /**
   * Returns a result value for the given alias.
   *
   * @param alias A custom alias provided in the query or an autogenerated alias in the form of
   *     'property_\d'
   * @return An aggregation result value for the given alias.
   * @throws NullPointerException if {@code alias} is not present in this result
   * @throws RuntimeException if the value is not numeric (for example, a {@link ValueType#NULL}
   *     result returned by {@code avg} when zero entities match)
   */
  public Long getLong(String alias) {
    Value<?> value = properties.get(alias);
    switch (value.getType()) {
      case DOUBLE:
        return ((Double) value.get()).longValue();
      case LONG:
        return (Long) value.get();
      default:
        throw new RuntimeException(
            String.format("Unsupported type %s received for alias '%s'.", value.getType(), alias));
    }
  }

  /**
   * Returns a result value for the given alias.
   *
   * @param alias A custom alias provided in the query or an autogenerated alias in the form of
   *     'property_\d'
   * @return An aggregation result value for the given alias.
   * @throws NullPointerException if {@code alias} is not present in this result
   * @throws RuntimeException if the value is not numeric (for example, a {@link ValueType#NULL}
   *     result returned by {@code avg} when zero entities match)
   */
  public Double getDouble(String alias) {
    Value<?> value = properties.get(alias);
    switch (value.getType()) {
      case LONG:
        return ((Long) value.get()).doubleValue();
      case DOUBLE:
        return (Double) value.get();
      default:
        throw new RuntimeException(
            String.format("Unsupported type %s received for alias '%s'.", value.getType(), alias));
    }
  }

  /**
   * Returns a result value for the given alias.
   *
   * @param alias A custom alias provided in the query or an autogenerated alias in the form of
   *     'property_\d'
   * @return An aggregation result value as a {@link Number} for the given alias.
   * @throws NullPointerException if {@code alias} is not present in this result
   * @throws RuntimeException if the value is not numeric (for example, a {@link ValueType#NULL}
   *     result returned by {@code avg} when zero entities match)
   */
  public Number getNumber(String alias) {
    Value<?> value = properties.get(alias);
    switch (value.getType()) {
      case LONG:
        return (Long) value.get();
      case DOUBLE:
        return (Double) value.get();
      default:
        throw new RuntimeException(
            String.format("Unsupported type %s received for alias '%s'.", value.getType(), alias));
    }
  }

  @Override
  public boolean equals(Object o) {
    if (this == o) {
      return true;
    }
    if (o == null || getClass() != o.getClass()) {
      return false;
    }
    AggregationResult that = (AggregationResult) o;
    return properties.equals(that.properties);
  }

  @Override
  public int hashCode() {
    return Objects.hash(properties);
  }

  @Override
  public String toString() {
    ToStringHelper toStringHelper = MoreObjects.toStringHelper(this);
    for (Entry<String, ? extends Value<?>> entry : properties.entrySet()) {
      toStringHelper.add(entry.getKey(), entry.getValue().get());
    }
    return toStringHelper.toString();
  }
}
